# ============ P6: 结果表 → LaTeX ============
_TEX_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
            "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}


def tex_escape(v: Any) -> str:
    """转义 LaTeX 特殊字符（保留下划线与百分号的语义正确性）。"""
    out = []
    for ch in str(v):
        out.append(_TEX_ESC.get(ch, ch))
    return "".join(out)


def table_to_latex(rows: List[Dict[str, Any]], *, columns: List[str],
                   caption: str = "", label: str = "tab:main",
                   bold_best: bool = True) -> str:
    """rows[0] 为表头数据；生成 booktabs 三线表。"""
    if not rows:
        return "% empty table\n"
    # 找每列最优（数值最大）用于加粗
    best = {}
    if bold_best:
        for c in columns:
            vals = []
            for r in rows:
                try:
                    vals.append((float(r.get(c)), r.get("model", "")))
                except (TypeError, ValueError):
                    pass
            if not vals:
                continue
            # 指标方向：↓/lower/less/越小越好 → min；否则 max
            low = any(k in str(c).lower() for k in ("↓", "lower", "less", "error", "runtime", "time"))
            chosen = min(vals) if low else max(vals)
            # 用行索引标记唯一最优（避免同名方法被一起加粗）
            idxs = [i for i, (v, _) in enumerate(vals) if v == chosen[0]]
            best[c] = idxs[0] if len(idxs) == 1 else -1
    head = " & ".join(["Model"] + [tex_escape(c) for c in columns]) + " \\\\"
    lines = ["\\begin{table}[t]", "\\centering",
             f"\\caption{{{tex_escape(caption)}}}", f"\\label{{{label}}}",
             "\\begin{tabular}{l" + "c" * len(columns) + "}", "\\toprule", head, "\\midrule"]
    for ri, r in enumerate(rows):
        cells = []
        for c in columns:
            v = tex_escape(r.get(c, ""))
            if bold_best and best.get(c) == ri:
                v = f"\\textbf{{{v}}}"
            cells.append(v)
        lines.append(" & ".join([tex_escape(r.get("model", ""))] + cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines) + "\n"


def csv_to_latex(csv_path: str | Path, *, caption: str = "",
                 label: str = "tab:main") -> str:
    p = Path(csv_path)
    with p.open(encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        return "% empty csv\n"
    cols = [c for c in rows[0].keys() if c != "model"]
    return table_to_latex(rows, columns=cols, caption=caption or p.stem, label=label)


# ============ P9: 章节骨架 ============
def build_section_skeleton(sections: List[str], *, run_id: str = "run",
                           claims: Optional[List[str]] = None,
                           words_per_section: int = 600) -> str:
    """按模板节名生成 markdown 骨架，每节带要引用的 claim 与字数预算。"""
    claims = claims or []
    out = [f"<!-- run_id={run_id} generated by paper_artifacts.build_section_skeleton -->", ""]
    for i, sec in enumerate(sections, 1):
        title = sec.replace(".", " · ").replace("_", " ").title()
        out.append(f"## {i}. {title}")
        out.append("")
        if sec.startswith(("method.", "exp.")):
            out.append(f"> 预算：{words_per_section} 词 | 引用 claim：{', '.join(claims) or '（待填）'}")
            out.append("")
            out.append("<!-- TODO: 正文（每句须可追溯到 claim 或引用） -->")
        else:
            out.append("<!-- TODO: 正文 -->")
        out.append("")
    return "\n".join(out)


# ============ P8: 绘图脚本 ============
def figure_script(kind: str, *, data_path: str = "results.csv",
                  out_path: str = "fig.pdf", title: str = "") -> str:
    """生成可执行的 matplotlib 脚本（architecture/bar/curve/case）。"""
    header = (
        "import matplotlib\nmatplotlib.use('Agg')\n"
        "import matplotlib.pyplot as plt\nimport csv\n\n"
        f"TITLE = {title!r}\n"
        f"OUT = {out_path!r}\n"
        f"DATA = {data_path!r}\n\n")
    if kind == "architecture":
        return header + (
            "# 架构图：手工布局方框图（占位，需按 P1 modules 调整）\n"
            "fig, ax = plt.subplots(figsize=(8, 3))\n"
            "ax.axis('off')\n"
            "for i, name in enumerate(['Input', 'Module A', 'Module B', 'Output']):\n"
            "    ax.add_patch(plt.Rectangle((i*2, 0.5), 1.5, 1, fill=False, lw=1.5))\n"
            "    ax.text(i*2+0.75, 1.0, name, ha='center', va='center', fontsize=9)\n"
            "    if i < 3:\n"
            "        ax.annotate('', xy=(i*2+2, 1.0), xytext=(i*2+1.5, 1.0),\n"
            "                    arrowprops=dict(arrowstyle='->'))\n"
            "ax.set_xlim(-0.2, 8.2); ax.set_ylim(0, 2)\n"
            "ax.set_title(TITLE)\nfig.tight_layout(); fig.savefig(OUT, bbox_inches='tight')\n")
    if kind == "bar":
        return header + (
            "models, values = [], []\n"
            "with open(DATA, encoding='utf-8-sig') as f:\n"
            "    r = list(csv.DictReader(f))\n"
            "    key = [k for k in r[0] if k != 'model'][0]\n"
            "    models = [x['model'] for x in r]; values = [float(x[key]) for x in r]\n"
            "fig, ax = plt.subplots(figsize=(6, 3))\n"
            "ax.bar(models, values); ax.set_ylabel(key); ax.set_title(TITLE)\n"
            "plt.xticks(rotation=30, ha='right')\n"
            "fig.tight_layout(); fig.savefig(OUT)\n")
    return header + (
        "fig, ax = plt.subplots(figsize=(5, 3))\n"
        "ax.plot([0, 1], [0, 1], label='demo')\nax.legend(); ax.set_title(TITLE)\n"
        "fig.tight_layout(); fig.savefig(OUT)\n")
